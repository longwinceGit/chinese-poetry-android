function toPinyinList(text) {
  if (!text) return [];
  var result = [];
  for (var i = 0; i < text.length; i++) {
    var c = text[i];
    var py = PINYIN_MAP[c];
    result.push(py || '');
  }
  return result;
}

function toTonePinyin(char) {
  return PINYIN_MAP[char] || char;
}

function hasPinyin(char) {
  return !!PINYIN_MAP[char];
}

